-- Todos and Calendar Events, each scoped to a Workspace. Times are epoch seconds.
CREATE TABLE todos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id text NOT NULL DEFAULT 'local' REFERENCES workspaces,
    title text NOT NULL CHECK(length(btrim(title)) BETWEEN 1 AND 500),
    completed boolean NOT NULL DEFAULT false
);
CREATE TABLE calendar_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id text NOT NULL DEFAULT 'local' REFERENCES workspaces,
    title text NOT NULL CHECK(length(btrim(title)) BETWEEN 1 AND 120),
    starts_at bigint NOT NULL,
    ends_at bigint NOT NULL CHECK(ends_at >= starts_at)
);
CREATE INDEX calendar_events_workspace_start ON calendar_events(workspace_id, starts_at);
